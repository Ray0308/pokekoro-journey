// Build this game's regional pools from reviewed rules, local types/stats and pinned evolution data.
const fs = require('node:fs'),
  path = require('node:path'),
  vm = require('node:vm'),
  crypto = require('node:crypto');
const root = path.resolve(__dirname, '..'),
  read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const rules = JSON.parse(read('data/map-encounter-rules.json'));
const csv = read('data/reference/pokemon-species.csv');
if (crypto.createHash('sha256').update(csv).digest('hex') !== rules.speciesSource.sha256)
  throw Error('Species source hash mismatch');
const lines = csv.trim().split(/\r?\n/),
  columns = lines.shift().split(','),
  species = {};
for (const line of lines) {
  const row = Object.fromEntries(line.split(',').map((v, i) => [columns[i], v]));
  species[+row.id] = row;
}
const context = vm.createContext({});
for (const f of [
  'pokemon-data.generated.js',
  'pokemon-stats.generated.js',
  'pokemon-battle-stats.js',
  'pokemon-data.js',
  'map-config.js',
  'rainbow-config.js',
])
  vm.runInContext(read(f), context, { filename: f });
const game = vm.runInContext(
  '({mons:POKEDEX, normal:NORMAL_ENCOUNTER_IDS, maps:MAPS, order:MAP_ORDER})',
  context,
);
const stages = {};
function stage(id, seen = new Set()) {
  if (stages[id] !== undefined) return stages[id];
  if (seen.has(id) || !species[id]) throw Error('Broken evolution ' + id);
  seen.add(id);
  const parent = +species[id].evolves_from_species_id;
  return (stages[id] = parent ? Math.min(2, stage(parent, seen) + 1) : 0);
}
const metadata = JSON.parse(read('data/pokemon.json')).pokemon;
const categories = {};
for (const mon of game.mons) {
  const names = metadata[mon.id - 1].types;
  const category = rules.categoryPriority.find(([, types]) =>
    types.some((t) => names.includes(t)),
  )?.[0];
  if (!category) throw Error('Unclassified ' + mon.id);
  categories[mon.id] = category;
  stage(mon.id);
}
const pools = {};
for (const id of game.order) {
  const rule = rules.maps[id];
  if (!rule) throw Error('Missing map rule ' + id);
  pools[id] = game.normal
    .filter((n) => {
      const mon = game.mons[n - 1];
      const total = Object.values(mon.stats).reduce((a, b) => a + b, 0);
      return (
        (rule.categories.includes(categories[n]) || rule.seeds.includes(n)) &&
        stages[n] <= rule.maxStage &&
        (rule.maxBST === null || total <= rule.maxBST)
      );
    })
    .map((n) => [
      n,
      rules.stageWeights[stages[n]] * (rule.seeds.includes(n) ? rules.seedMultiplier : 1),
    ]);
  if (!pools[id].length) throw Error('Empty pool ' + id);
}
const covered = new Set(
  Object.values(pools)
    .flat()
    .map(([id]) => id),
);
const missing = game.normal.filter((id) => !covered.has(id));
if (missing.length) throw Error('Unreachable normal Pokemon: ' + missing.join(','));
const generated =
  "'use strict';\n// Generated by scripts/build-map-encounters.cjs. Do not edit.\n// prettier-ignore\nconst MAP_ENCOUNTERS = Object.freeze(Object.fromEntries(Object.entries(" +
  JSON.stringify(pools) +
  ').map(([id,entries])=>[id,Object.freeze(entries.map(entry=>Object.freeze(entry)))])));\n';
const name = (id) => game.mons[id - 1].label;
let doc =
  '# 地域別の出現候補・ボス情報\n\n0.9.2.85。全世代を残す本作独自の設定で、原作の生息地・出現率を再現した表ではない。伝説・幻は通常抽選から除外し、にじのくもを維持。ハナダの洞窟最深部のミュウツーは既存の例外。\n\n進化段階の重みは10/4/1、地域の代表候補はさらに3倍。同じマップでは遭遇のたびに独立抽選。捕獲確率・敵HP・報酬は変更しない。\n\n';
for (const id of game.order) {
  const rule = rules.maps[id];
  doc +=
    '## ' +
    game.maps[id].name +
    '\n\n' +
    rule.theme +
    '。候補' +
    pools[id].length +
    '種。進化段階上限' +
    rule.maxStage +
    '、種族値合計上限' +
    (rule.maxBST ?? 'なし') +
    '。\n\n' +
    pools[id].map(([n, w]) => `${name(n)}（${n}・重み${w}）`).join('、') +
    '\n\n';
}
const rosters = JSON.parse(read('data/trainer-rosters.json'));
doc += '## ボスの設定元（編成は変更なし）\n\n| マップ | 相手・設定元 |\n| --- | --- |\n';
for (const id of game.order) {
  let text;
  if (game.maps[id].boss.wild)
    text = id === 'safari-zone' ? 'ガルーラ／ラッキー／ケンタロスから抽選' : 'ミュウツー';
  else if (rosters.bosses[id])
    text =
      game.maps[id].boss.name +
      '：' +
      rosters.bosses[id].fixedIds.map(name).join('・') +
      '（既存の再戦入替あり）';
  else if (['ss-anne', 'indigo-champion'].includes(id)) text = 'ライバル：保存済みの系統と専用編成';
  else
    text =
      rosters.maps[id].bossClasses.map((c) => rosters.classes[c].name).join('／') +
      '：職業別の専用抽選';
  doc += '| ' + game.maps[id].name + ' | ' + text + ' |\n';
}
for (const [f, content] of [
  ['map-encounters.generated.js', generated],
  ['docs/MAP_ENCOUNTERS.md', doc],
]) {
  if (process.argv.includes('--check')) {
    if (read(f) !== content) throw Error('Stale ' + f);
  } else fs.writeFileSync(path.join(root, f), content);
}
console.log(
  'Regional pools:',
  game.order.length,
  'maps,',
  covered.size,
  'normal species, zero omissions',
);
